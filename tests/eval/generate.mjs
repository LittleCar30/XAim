import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import bugs from './catalog/bugs.mjs';
import additions from './catalog/test-additions.mjs';
import refactors from './catalog/refactors.mjs';
import crossFile from './catalog/cross-file.mjs';
import depsReview from './catalog/deps-review.mjs';
import { hooks } from './catalog/hooks.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const tasks = [...bugs, ...additions, ...refactors, ...crossFile, ...depsReview];
if (tasks.length !== 30) throw new Error('The catalog must contain 30 tasks');
const tsPackage = {
  name: 'eval-fixture', version: '1.0.0', private: true, type: 'module', engines: { node: '>=18' },
  scripts: { test: 'tsc -p tsconfig.json && node --test tests/*.test.mjs' },
  devDependencies: { typescript: '5.5.4' },
};
const tsLock = {
  name: 'eval-fixture', version: '1.0.0', lockfileVersion: 3, requires: true,
  packages: {
    '': { name: 'eval-fixture', version: '1.0.0', devDependencies: { typescript: '5.5.4' }, engines: { node: '>=18' } },
    'node_modules/typescript': {
      version: '5.5.4', resolved: 'https://registry.npmjs.org/typescript/-/typescript-5.5.4.tgz',
      integrity: 'sha512-Mtq29sKDAEYP7aljRgtPOpTvOfbwRWlS6dPRzwjdE+C0R4brX/GUyhHSecbHMFLNBLcJIPt9nl9yG5TZ1weH+Q==',
      dev: true, bin: { tsc: 'bin/tsc', tsserver: 'bin/tsserver' }, engines: { node: '>=14.17' },
    },
  },
};
const json = value => `${JSON.stringify(value, null, 2)}\n`;
const common = language => {
  if (language === 'TS') return {
    'package.json': json(tsPackage), 'package-lock.json': json(tsLock),
    'tsconfig.json': json({ compilerOptions: { target: 'ES2021', module: 'NodeNext', moduleResolution: 'NodeNext', strict: true, rootDir: 'src', outDir: 'dist' }, include: ['src/**/*.ts'] }),
  };
  if (language === 'Go') return { 'go.mod': 'module eval.local/fixture\n\ngo 1.20\n' };
  if (language === 'Rust') return {
    'Cargo.toml': '[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2021"\n',
    'Cargo.lock': '# This file is automatically @generated by Cargo.\nversion = 4\n[[package]]\nname = "fixture"\nversion = "0.1.0"\n',
  };
  return {};
};
const commands = { TS: ['npm', 'test'], Python: ['python', '-m', 'unittest', 'discover', '-s', 'tests'], Rust: ['cargo', 'test', '--offline', '--locked'], Go: ['go', 'test', './...'] };
let patch = '*** Begin Patch\n';
function add(file, content) {
  const absolute = path.join(root, file).replaceAll('\\', '/');
  let previous;
  try { previous = readFileSync(absolute, 'utf8'); } catch { /* New task file. */ }
  if (previous === content) return;
  if (previous !== undefined) {
    patch += `*** Update File: ${absolute}\n@@\n${previous.trimEnd().split('\n').map(line => `-${line}`).join('\n')}\n${content.trimEnd().split('\n').map(line => `+${line}`).join('\n')}\n`;
  } else {
    patch += `*** Add File: ${absolute}\n${content.trimEnd().split('\n').map(line => `+${line}`).join('\n')}\n`;
  }
}
function diff(file, before, after) {
  const old = before?.trimEnd().split('\n') || [];
  const next = after.trimEnd().split('\n');
  return `diff --git a/${file} b/${file}\n${before === undefined ? 'new file mode 100644\n' : ''}--- ${before === undefined ? '/dev/null' : `a/${file}`}\n+++ b/${file}\n@@ -${old.length ? `1,${old.length}` : '0,0'} +1,${next.length} @@\n${old.map(line => `-${line}\n`).join('')}${next.map(line => `+${line}\n`).join('')}`;
}
for (const task of tasks) {
  const initial = { ...common(task.language), ...task.files };
  initial['.gitignore'] = 'node_modules/\ndist/\ntarget/\n__pycache__/\n*.pyc\n.venv/\n';
  const solution = { ...task.solution };
  if (task.localNpm) {
    const pkg = structuredClone(tsPackage);
    pkg.dependencies = { 'slug-kit': 'file:vendor/slug-v1' };
    initial['package.json'] = json(pkg);
    const lock = structuredClone(tsLock);
    lock.packages[''].dependencies = { 'slug-kit': 'file:vendor/slug-v1' };
    lock.packages['node_modules/slug-kit'] = { resolved: 'vendor/slug-v1', link: true };
    lock.packages['vendor/slug-v1'] = { name: 'slug-kit', version: '1.0.0' };
    initial['package-lock.json'] = json(lock);
    pkg.dependencies = { 'slug-kit': 'file:vendor/slug-v2' };
    solution['package.json'] = json(pkg);
    delete lock.packages['vendor/slug-v1'];
    lock.packages[''].dependencies = pkg.dependencies;
    lock.packages['node_modules/slug-kit'] = { resolved: 'vendor/slug-v2', link: true };
    lock.packages['vendor/slug-v2'] = { name: 'slug-kit', version: '2.0.0' };
    solution['package-lock.json'] = json(lock);
  }
  const required = Object.keys(solution);
  const spec = { id: task.id, category: task.category, language: task.language, allowed: required, required, prepare: task.prepare || (task.language === 'TS' && task.category !== 'review' ? [['npm', 'ci', '--ignore-scripts', '--no-audit', '--no-fund']] : []), commands: task.category === 'review' ? [] : [commands[task.language]], mutations: task.mutations || [] };
  if (task.language === 'Rust') for (const mutation of spec.mutations) mutation.command = commands.Rust;
  const base = `tasks/${task.id}/`;
  for (const [name, content] of Object.entries(initial)) add(`${base}repo/${name}`, content);
  add(`${base}task.json`, json(spec));
  add(`${base}task.md`, `# 任务\n${task.title}\n\n${task.description}\n\n# 验证\n${task.category === 'review' ? 'bash ../verify.sh' : commands[task.language].join(' ')}\n\n评测侧使用 bash verify.sh /path/to/work-repo 检查全部通过标准。\n\n# 期望\n- ${task.description}\n- 仅允许修改或新增：${required.join('、')}\n- 验证脚本退出码为 0${task.mutations ? '，且所有变异实现均被测试识别' : ''}\n`);
  add(`${base}verify.sh`, '#!/usr/bin/env bash\nset -euo pipefail\ntask_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"\nrepo_dir="${1:-$task_dir/repo}"\nnode "$task_dir/verify.mjs" "$task_dir" "$repo_dir"\n');
  add(`${base}verify.mjs`, readFileSync(path.join(root, 'verify.mjs'), 'utf8'));
  add(`${base}expected.diff`, Object.entries(solution).map(([file, content]) => diff(file, initial[file], content)).join(''));
  if (hooks[task.id]) add(`${base}check.mjs`, hooks[task.id]);
}
patch += '*** End Patch\n';
process.stdout.write(patch);
